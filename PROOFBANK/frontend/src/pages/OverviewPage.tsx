import { useState } from 'react';
import {
  AlertTriangle,
  ArrowLeftRight,
  CheckCircle2,
  Clock,
  LayoutDashboard,
  RefreshCw,
  Users,
  Wallet,
  XCircle,
  Undo2,
  Coins,
} from 'lucide-react';
import { PageHeader } from '../components/layout/PageHeader';
import { SimulatedNotice } from '../components/layout/Environment';
import { Panel } from '../components/ui/Panel';
import { MetricTile } from '../components/dashboard/MetricTile';
import { RangeSelector } from '../components/dashboard/RangeSelector';
import { VolumeChart } from '../components/dashboard/VolumeChart';
import { StatusBreakdown } from '../components/dashboard/StatusBreakdown';
import { RecentTransactionsTable } from '../components/dashboard/RecentTransactionsTable';
import { EventFeed } from '../components/dashboard/EventFeed';
import { ScenarioExecutionsTable } from '../components/dashboard/ScenarioExecutionsTable';
import { DeliveryTable } from '../components/dashboard/DeliveryTable';
import { ProviderHealthPanel } from '../components/dashboard/ProviderHealthPanel';
import { SimulationStatePanel } from '../components/dashboard/SimulationStatePanel';
import { QuickActions } from '../components/dashboard/QuickActions';
import { ErrorState } from '../components/ui/States';
import {
  useDashboardSummary,
  useInfrastructureHealth,
  useRecentDeliveries,
  useRecentEvents,
  useRecentScenarioExecutions,
  useRecentTransactions,
} from '../hooks/useDashboard';
import { useNow } from '../hooks/useSimulationStatus';
import { formatMoney, formatMoneyCompact } from '../lib/format';
import type { DashboardRange } from '../types/domain';

const rangeLabels: Record<DashboardRange, string> = {
  '24h': 'last 24 hours',
  '7d': 'last 7 days',
  '30d': 'last 30 days',
};

/**
 * Overview dashboard. Every figure is rendered from the data source; the
 * trend deltas use the previous-period values the source reports.
 */
export function OverviewPage() {
  const [range, setRange] = useState<DashboardRange>('24h');
  const summary = useDashboardSummary(range);
  const transactions = useRecentTransactions(6);
  const events = useRecentEvents(6);
  const executions = useRecentScenarioExecutions(5);
  const deliveries = useRecentDeliveries(6);
  const health = useInfrastructureHealth();
  const now = useNow(10_000);

  const metrics = summary.data?.metrics;
  const activity = summary.data?.activity;
  const previous = metrics?.previousPeriod;

  return (
    <>
      <PageHeader
        title="Overview"
        sectionId="overview"
        description={`Operational metrics and activity across the simulated banking environment (${rangeLabels[range]}).`}
        actions={
          <>
            <SimulatedNotice />
            <RangeSelector value={range} onChange={setRange} />
          </>
        }
        notice={
          <div className="flex flex-wrap items-center gap-2 rounded-control border border-line bg-surface px-3 py-2 text-xs text-ink-secondary">
            <LayoutDashboard aria-hidden className="size-3.5 text-brand" />
            <span>
              Metrics, activity, events and delivery data are generated by the
              simulated data source and refresh on a visible cadence.
            </span>
            <span className="ml-auto flex items-center gap-1.5 whitespace-nowrap">
              <RefreshCw aria-hidden className="size-3" />
              {summary.dataUpdatedAt
                ? `Updated ${new Date(summary.dataUpdatedAt).toLocaleTimeString('en-GB')}`
                : 'Refreshing…'}
            </span>
          </div>
        }
      />

      <div className="flex flex-col gap-5">
        {/* ------------------------------------------------- metric tiles */}
        {summary.error ? (
          <ErrorState
            error={summary.error}
            onRetry={() => void summary.refetch()}
          />
        ) : (
          <section aria-label="Summary metrics" className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
            <MetricTile
              label="Simulated customers"
              value={(metrics?.customers.total ?? 0).toLocaleString('en-NG')}
              hint={`${metrics?.customers.newInPeriod ?? 0} added in range`}
              icon={<Users aria-hidden className="size-4" />}
              loading={summary.isPending}
            />
            <MetricTile
              label="Active accounts"
              value={(metrics?.accounts.active ?? 0).toLocaleString('en-NG')}
              hint={`${metrics?.accounts.total ?? 0} accounts total`}
              icon={<Wallet aria-hidden className="size-4" />}
              loading={summary.isPending}
            />
            <MetricTile
              label="Settled volume"
              value={
                metrics
                  ? formatMoneyCompact({
                      amountMinor: metrics.volumeMinor,
                      currency: metrics.currency,
                    })
                  : '—'
              }
              hint="Value of successful transactions"
              icon={<Coins aria-hidden className="size-4" />}
              loading={summary.isPending}
              comparison={
                metrics
                  ? { current: metrics.volumeMinor, previous: previous?.volumeMinor ?? 0 }
                  : undefined
              }
              risingTone="warning"
            />
            <MetricTile
              label="Successful"
              value={(metrics?.transactions.successful ?? 0).toLocaleString('en-NG')}
              hint="Settled transactions"
              icon={<CheckCircle2 aria-hidden className="size-4" />}
              tone="success"
              loading={summary.isPending}
              comparison={
                metrics
                  ? {
                      current: metrics.transactions.successful,
                      previous: previous?.successful ?? 0,
                    }
                  : undefined
              }
            />
            <MetricTile
              label="Failed"
              value={(metrics?.transactions.failed ?? 0).toLocaleString('en-NG')}
              hint="No funds moved"
              icon={<XCircle aria-hidden className="size-4" />}
              tone="danger"
              loading={summary.isPending}
              comparison={
                metrics
                  ? { current: metrics.transactions.failed, previous: previous?.failed ?? 0 }
                  : undefined
              }
              risingTone="danger"
            />
            <MetricTile
              label="Pending"
              value={(metrics?.transactions.pending ?? 0).toLocaleString('en-NG')}
              hint="Awaiting settlement"
              icon={<Clock aria-hidden className="size-4" />}
              tone="warning"
              loading={summary.isPending}
            />
            <MetricTile
              label="Reversed"
              value={(metrics?.transactions.reversed ?? 0).toLocaleString('en-NG')}
              hint="Compensating entries posted"
              icon={<Undo2 aria-hidden className="size-4" />}
              tone="danger"
              loading={summary.isPending}
              comparison={
                metrics
                  ? {
                      current: metrics.transactions.reversed,
                      previous: previous?.reversed ?? 0,
                    }
                  : undefined
              }
              risingTone="danger"
            />
            <MetricTile
              label="Total transactions"
              value={(metrics?.transactions.total ?? 0).toLocaleString('en-NG')}
              hint={`${metrics?.transactions.created ?? 0} still awaiting processing`}
              icon={<ArrowLeftRight aria-hidden className="size-4" />}
              loading={summary.isPending}
              comparison={
                metrics
                  ? {
                      current: metrics.transactions.total,
                      previous: previous?.transactions ?? 0,
                    }
                  : undefined
              }
            />
          </section>
        )}

        {/* ------------------------------------------------- activity charts */}
        <div className="grid gap-5 xl:grid-cols-3">
          <VolumeChart
            data={activity?.volume ?? []}
            range={range}
            loading={summary.isPending}
          />
          <StatusBreakdown
            data={activity?.statusDistribution ?? []}
            loading={summary.isPending}
          />
        </div>

        {/* ------------------------------------------------- recent records */}
        <div className="grid gap-5 xl:grid-cols-3">
          <RecentTransactionsTable
            transactions={transactions.data}
            loading={transactions.isPending}
            error={transactions.error}
            onRetry={() => void transactions.refetch()}
          />
          <EventFeed
            events={events.data}
            loading={events.isPending}
            error={events.error}
            onRetry={() => void events.refetch()}
          />
        </div>

        {/* ------------------------------------------- scenarios + deliveries */}
        <div className="grid gap-5 xl:grid-cols-2">
          <ScenarioExecutionsTable
            executions={executions.data}
            loading={executions.isPending}
            error={executions.error}
            onRetry={() => void executions.refetch()}
          />
          <DeliveryTable
            deliveries={deliveries.data}
            loading={deliveries.isPending}
            error={deliveries.error}
            onRetry={() => void deliveries.refetch()}
          />
        </div>

        {/* -------------------------------------- simulation state + actions */}
        <div className="grid gap-5 xl:grid-cols-2">
          <SimulationStatePanel status={metrics?.simulation} />
          <QuickActions />
        </div>

        {/* ------------------------------------------------------ provider health */}
        <ProviderHealthPanel
          services={health.data?.services}
          incidents={health.data?.incidents}
          loading={health.isPending}
          error={health.error}
          onRetry={() => void health.refetch()}
        />

        {/* ------------------------------------------------------ period totals */}
        {metrics && (
          <Panel
            title="Period totals"
            description={`Exact figures for the ${rangeLabels[range]} period.`}
          >
            <dl className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
              <PeriodTotal
                label="Settled volume"
                value={formatMoney({
                  amountMinor: metrics.volumeMinor,
                  currency: metrics.currency,
                })}
              />
              <PeriodTotal
                label="Events emitted"
                value={metrics.events.emittedInPeriod.toLocaleString('en-NG')}
              />
              <PeriodTotal
                label="Deliveries succeeded"
                value={metrics.events.delivered.toLocaleString('en-NG')}
              />
              <PeriodTotal
                label="Deliveries failed"
                value={metrics.events.failed.toLocaleString('en-NG')}
              />
            </dl>
            {metrics.infrastructure.openIncidents > 0 && (
              <p className="mt-3 flex items-center gap-2 text-xs text-warning">
                <AlertTriangle aria-hidden className="size-3.5" />
                {metrics.infrastructure.openIncidents} open simulated
                infrastructure incident
                {metrics.infrastructure.openIncidents === 1 ? '' : 's'} in this
                period.
              </p>
            )}
            <p className="mt-2 text-[0.6875rem] text-ink-secondary">
              Snapshot taken {new Date(now).toLocaleTimeString('en-GB')}.
            </p>
          </Panel>
        )}
      </div>
    </>
  );
}

function PeriodTotal({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-control border border-line bg-surface-muted/40 p-3">
      <dt className="text-xs text-ink-secondary">{label}</dt>
      <dd className="mt-1 text-lg font-semibold tabular-nums text-ink">{value}</dd>
    </div>
  );
}
